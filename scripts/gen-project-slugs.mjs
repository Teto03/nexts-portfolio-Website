// Writes lib/project-slugs.ts with the slugs of the published projects.
// The view counter API runs on the edge runtime, which cannot read the
// filesystem, so it validates incoming slugs against this generated list.
import fs from "node:fs";
import path from "node:path";
import { parse } from "yaml";

const dir = path.join(process.cwd(), "content", "projects");
const slugs = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".mdx"))
  .filter((f) => {
    const m = fs.readFileSync(path.join(dir, f), "utf8").match(/^---\r?\n([\s\S]*?)\r?\n---/);
    return m && (parse(m[1]) ?? {}).published !== false;
  })
  .map((f) => f.replace(/\.mdx$/, ""))
  .sort();

const out = `// Generated by scripts/gen-project-slugs.mjs. Do not edit by hand.
export const PROJECT_SLUGS: ReadonlySet<string> = new Set([
${slugs.map((s) => `  ${JSON.stringify(s)},`).join("\n")}
]);
`;
fs.writeFileSync(path.join(process.cwd(), "lib", "project-slugs.ts"), out);
console.log(`project-slugs: ${slugs.length} slugs`);
